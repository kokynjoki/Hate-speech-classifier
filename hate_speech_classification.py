"""Data pre-processing"""

def clean_tweet(text):
    # Ensure text is treated as a string and handle potential leading/trailing list-like characters if present
    if isinstance(text, str) and text.startswith("['") and text.endswith("']"):
        text = text[2:-2] # Remove the leading "['" and trailing "']"

    review = str(text) # Ensure it's a string
    review = re.sub(r"http\S+|www\S+|@\w+|#\w+", "", review) # Remove URLs, mentions, and hashtags
    review = re.sub('[^a-zA-Z]',' ', review) # Remove numbers and special characters, keep only letters
    review = review.lower() # Lowercase
    review = review.split() # Tokenize
    # Remove empty strings from tokenization (e.g., from multiple spaces) and then lemmatize and remove stopwords
    review = [lemmatizer.lemmatize(word) for word in review if word and word not in stopwords.words('english')]
    review = ' '.join(review)
    return review

hate_speech["clean_tweet"] = hate_speech['Tweet'].apply(clean_tweet)

"""Text - Vectors

TF-IDF(Term Frequence-Inverse Document
Frequency)
"""

tfidf = TfidfVectorizer(max_features=5000, ngram_range=(1, 2), min_df=2, max_df=0.9,stop_words="english")
